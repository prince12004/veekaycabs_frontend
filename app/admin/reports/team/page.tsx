"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { CalendarCheck, CheckCircle, Clock, Loader2, UsersRound, XCircle } from "lucide-react";
import toast from "react-hot-toast";
import { adminReportsApi } from "@/lib/api";

type Counts = { total: number; pending: number; confirmed: number; active: number; completed: number; cancelled: number };
type Row = Counts & { name: string; isMember: boolean };
type Report = { rows: Row[]; unassigned: Counts; overall: Counts };
type Preset = "today" | "week" | "month" | "all" | "custom";

const UNASSIGNED = "__unassigned__";
const PRESETS: { key: Preset; label: string }[] = [
  { key: "today", label: "Today" },
  { key: "week", label: "This Week" },
  { key: "month", label: "This Month" },
  { key: "all", label: "All Time" },
  { key: "custom", label: "Custom Range" },
];
const COLUMNS: { key: keyof Counts; label: string; status?: string }[] = [
  { key: "total", label: "Total Bookings" },
  { key: "completed", label: "Completed", status: "Completed" },
  { key: "pending", label: "Pending", status: "Pending" },
  { key: "cancelled", label: "Cancelled", status: "Cancelled" },
  { key: "confirmed", label: "Confirmed", status: "Confirmed" },
  { key: "active", label: "Active", status: "Active" },
];

const ymd = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

// Weeks run Monday to Sunday.
const presetRange = (preset: Preset) => {
  const now = new Date();
  if (preset === "today") return { from: ymd(now), to: ymd(now) };
  if (preset === "week") {
    const monday = new Date(now);
    monday.setDate(now.getDate() - ((now.getDay() + 6) % 7));
    return { from: ymd(monday), to: ymd(now) };
  }
  if (preset === "month") return { from: ymd(new Date(now.getFullYear(), now.getMonth(), 1)), to: ymd(now) };
  return { from: "", to: "" };
};

export default function TeamBookingReportPage() {
  const [preset, setPreset] = useState<Preset>("month");
  const [customFrom, setCustomFrom] = useState("");
  const [customTo, setCustomTo] = useState("");
  const [member, setMember] = useState("");
  const [report, setReport] = useState<Report | null>(null);
  const [loading, setLoading] = useState(true);

  const { from, to } = preset === "custom" ? { from: customFrom, to: customTo } : presetRange(preset);

  useEffect(() => {
    const params: { from?: string; to?: string } = {};
    if (from) params.from = from;
    if (to) params.to = to;
    setLoading(true);
    adminReportsApi.getTeamBookings(params)
      .then(({ data }) => setReport(data.data))
      .catch(() => toast.error("Failed to load team report"))
      .finally(() => setLoading(false));
  }, [from, to]);

  const bookingsLink = (bookedBy: string, status?: string) => {
    const params = new URLSearchParams({ bookedBy });
    if (status) params.set("status", status);
    if (from) params.set("from", from);
    if (to) params.set("to", to);
    return `/admin/bookings?${params.toString()}`;
  };

  const rows = (report?.rows || []).filter((r) => (r.isMember || r.total > 0) && (!member || r.name === member));
  const showUnassigned = !!report && (!member || member === UNASSIGNED);
  const overall = report?.overall;
  const tiles = [
    { label: "All Bookings", value: overall?.total, icon: CalendarCheck, color: "#E8540A", bg: "#FFF3ED" },
    { label: "Completed", value: overall?.completed, icon: CheckCircle, color: "#10B981", bg: "#D1FAE5" },
    { label: "Pending", value: overall?.pending, icon: Clock, color: "#F59E0B", bg: "#FEF3C7" },
    { label: "Cancelled", value: overall?.cancelled, icon: XCircle, color: "#EF4444", bg: "#FEE2E2" },
  ];

  return (
    <div className="p-6 space-y-6">
      <div>
        <h1 className="font-syne font-black text-2xl text-[#0F0F1A]">Team Booking Report</h1>
        <p className="text-[#9090A8] text-sm mt-1">Bookings generated by each team member, by the date they were created. Click a count to see the bookings.</p>
      </div>

      <div className="bg-white rounded-2xl border border-[#E4E5EF] p-5 flex flex-wrap items-center gap-3">
        <div className="flex flex-wrap gap-2">
          {PRESETS.map((p) => (
            <button
              key={p.key}
              onClick={() => setPreset(p.key)}
              className={`px-3.5 py-2 rounded-xl text-sm font-semibold border transition-colors ${preset === p.key ? "bg-[#FFF3ED] border-[#E8540A] text-[#E8540A]" : "border-[#E4E5EF] text-[#4A4A6A] hover:border-[#E8540A]"}`}
            >
              {p.label}
            </button>
          ))}
        </div>
        {preset === "custom" && (
          <div className="flex flex-wrap items-center gap-2">
            <input type="date" aria-label="From date" value={customFrom} max={customTo || undefined} onChange={(e) => setCustomFrom(e.target.value)} className="border-[1.5px] border-[#E4E5EF] rounded-xl px-3 py-2 text-sm focus:border-[#E8540A] outline-none" />
            <span className="text-[#9090A8] text-sm">to</span>
            <input type="date" aria-label="To date" value={customTo} min={customFrom || undefined} onChange={(e) => setCustomTo(e.target.value)} className="border-[1.5px] border-[#E4E5EF] rounded-xl px-3 py-2 text-sm focus:border-[#E8540A] outline-none" />
          </div>
        )}
        <select aria-label="Team member" value={member} onChange={(e) => setMember(e.target.value)} className="sm:ml-auto border-[1.5px] border-[#E4E5EF] rounded-xl px-3 py-2 text-sm focus:border-[#E8540A] outline-none bg-white">
          <option value="">All team members</option>
          {(report?.rows || []).filter((r) => r.isMember || r.total > 0).map((r) => <option key={r.name} value={r.name}>{r.name}</option>)}
          <option value={UNASSIGNED}>Not assigned</option>
        </select>
      </div>

      <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
        {tiles.map(({ label, value, icon: Icon, color, bg }) => (
          <div key={label} className="bg-white rounded-2xl border border-[#E4E5EF] p-4 flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl flex items-center justify-center shrink-0" style={{ backgroundColor: bg }}>
              <Icon size={16} style={{ color }} />
            </div>
            <div>
              <p className="text-xl font-black text-[#0F0F1A] font-syne leading-none">{value ?? "—"}</p>
              <p className="text-[#9090A8] text-[10px] font-semibold uppercase tracking-wider mt-0.5">{label}</p>
            </div>
          </div>
        ))}
      </div>

      <div className="bg-white rounded-2xl border border-[#E4E5EF] overflow-hidden">
        {loading && !report ? (
          <div className="flex items-center justify-center gap-3 py-20 text-[#9090A8]">
            <Loader2 size={20} className="animate-spin" /> Loading report...
          </div>
        ) : !rows.length && !showUnassigned ? (
          <div className="py-20 text-center text-[#9090A8]">
            <UsersRound size={36} className="mx-auto mb-3 text-[#E4E5EF]" />
            <p className="font-semibold">No bookings found</p>
          </div>
        ) : (
          <div className={`overflow-x-auto transition-opacity ${loading ? "opacity-50" : ""}`}>
            <table className="w-full">
              <thead>
                <tr className="bg-[#F8F9FC] border-b border-[#E4E5EF]">
                  <th className="px-4 py-3.5 text-left text-[10px] font-bold uppercase tracking-widest text-[#9090A8]">Team Member</th>
                  {COLUMNS.map((c) => (
                    <th key={c.key} className="px-4 py-3.5 text-right text-[10px] font-bold uppercase tracking-widest text-[#9090A8] whitespace-nowrap">{c.label}</th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {rows.map((r) => (
                  <tr key={r.name} className="border-b border-[#E4E5EF] hover:bg-[#FFF3ED] transition-colors">
                    <td className="px-4 py-3.5 font-semibold text-[#0F0F1A] text-sm whitespace-nowrap">
                      {r.name}
                      {!r.isMember && <span className="ml-2 text-[10px] font-semibold text-[#9090A8]">Not on team</span>}
                    </td>
                    {COLUMNS.map((c) => (
                      <td key={c.key} className="px-4 py-3.5 text-right text-sm tabular-nums">
                        <CountLink count={r[c.key]} href={bookingsLink(r.name, c.status)} strong={c.key === "total"} />
                      </td>
                    ))}
                  </tr>
                ))}
                {showUnassigned && report && (
                  <tr className="border-b border-[#E4E5EF] hover:bg-[#FFF3ED] transition-colors">
                    <td className="px-4 py-3.5 text-[#4A4A6A] text-sm whitespace-nowrap">Not assigned</td>
                    {COLUMNS.map((c) => (
                      <td key={c.key} className="px-4 py-3.5 text-right text-sm tabular-nums">
                        <CountLink count={report.unassigned[c.key]} href={bookingsLink(UNASSIGNED, c.status)} strong={c.key === "total"} />
                      </td>
                    ))}
                  </tr>
                )}
              </tbody>
              {!member && overall && (
                <tfoot>
                  <tr className="bg-[#F8F9FC]">
                    <td className="px-4 py-3.5 font-black text-[#0F0F1A] text-sm">All team members</td>
                    {COLUMNS.map((c) => (
                      <td key={c.key} className="px-4 py-3.5 text-right text-sm font-black text-[#0F0F1A] tabular-nums">{overall[c.key]}</td>
                    ))}
                  </tr>
                </tfoot>
              )}
            </table>
          </div>
        )}
      </div>
    </div>
  );
}

function CountLink({ count, href, strong }: { count: number; href: string; strong: boolean }) {
  if (!count) return <span className="text-[#9090A8]">0</span>;
  return <Link href={href} className={`text-[#E8540A] hover:underline ${strong ? "font-black" : "font-semibold"}`}>{count}</Link>;
}
